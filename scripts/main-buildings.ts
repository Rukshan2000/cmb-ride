// Colombo main-building list for contributors: every OSM-named building plus unnamed towers (>= 40 m) in the map area,
// tiered by importance and grouped by neighbourhood, with OSM + street-level links and modelling status.
// Run: node scripts/main-buildings.ts   -> docs/colombo-main-buildings.md
// Data © OpenStreetMap contributors (ODbL). Re-run after `npm run fetch-map` or after adding records/models.

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { unproject } from '../src/map/MapProjection.ts';
import type { BuildingData, ChunkData, MapIndex } from '../src/map/MapTypes.ts';

const DIR = 'public/data/chunks', OUT = 'docs/colombo-main-buildings.md', TALL = 40;

const index: MapIndex = JSON.parse(readFileSync('public/data/index.json', 'utf8'));
const records: { osm?: number[]; model?: string; references?: unknown[]; confidence?: string; buildingType?: string }[] =
  JSON.parse(readFileSync('public/data/buildings/records.json', 'utf8'));
const landmarkIds = new Set(records.filter(r => r.buildingType === 'landmark').flatMap(r => r.osm ?? []));
const status = new Map<number, string>();
for (const r of records) for (const id of r.osm ?? [])
  status.set(id, r.model ? `modelled (${r.confidence ?? '?'})` : r.references?.length ? 'photos collected' : 'record only');

type Row = { b: BuildingData; x: number; z: number; tier: 1 | 2 | 3; area: string };
const rows: Row[] = [];
const seen = new Set<number>();
for (const f of readdirSync(DIR)) {
  const c: ChunkData = JSON.parse(readFileSync(`${DIR}/${f}`, 'utf8'));
  for (const b of c.buildings) {
    if (seen.has(b.id) || (!b.n && b.h < TALL)) continue;
    seen.add(b.id);
    let x = 0, z = 0;
    for (let i = 0; i < b.p.length; i += 2) { x += b.p[i]; z += b.p[i + 1]; }
    x /= b.p.length / 2; z /= b.p.length / 2;
    const icon = landmarkIds.has(b.id) || b.h >= 80;
    const major = b.n && (b.h >= 25 || /^(civic|religious|office|commercial)$/.test(b.k));
    rows.push({ b, x, z, tier: icon ? 1 : major ? 2 : 3, area: nearestPlace(x, z) });
  }
}

function nearestPlace(x: number, z: number) {
  let best = 'Other', d = Infinity;
  for (const p of index.places) { const e = Math.hypot(p.x - x, p.z - z); if (e < d) { d = e; best = p.name; } }
  return best;
}

const TIER = { 1: '★★★ Icon', 2: '★★ Major', 3: '★ Local' } as const;
const esc = (s: string) => s.replace(/\|/g, '/');
const line = (r: Row) => {
  const [lat, lon] = unproject(r.x, r.z), b = r.b;
  const name = b.n ? esc(b.n) : `*Unnamed ${Math.round(b.h)} m tower*`;
  const ht = `${b.l} fl / ${Math.round(b.h)} m${b.e ? ' (est.)' : ''}`;
  return `| ${status.get(b.id)?.startsWith('modelled') ? '[x]' : '[ ]'} | ${name} | ${TIER[r.tier]} | ${b.k} | ${ht} | ` +
    `[way ${b.id}](https://www.openstreetmap.org/way/${b.id}) | [photos](https://www.mapillary.com/app/?lat=${lat.toFixed(6)}&lng=${lon.toFixed(6)}&z=19) · ` +
    `[in game](/?at=${lat.toFixed(6)},${lon.toFixed(6)},0) | ${status.get(b.id) ?? 'to do'} |`;
};

const byArea = new Map<string, Row[]>();
for (const r of rows) (byArea.get(r.area) ?? byArea.set(r.area, []).get(r.area)!).push(r);
const areas = [...byArea].sort((a, b) => Math.min(...a[1].map(r => r.tier)) - Math.min(...b[1].map(r => r.tier)) || b[1].length - a[1].length);
const count = (t: number) => rows.filter(r => r.tier === t).length;
const done = rows.filter(r => status.get(r.b.id)?.startsWith('modelled')).length;

const md = [
  '# Colombo main buildings: modelling list',
  '',
  `Generated by \`node scripts/main-buildings.ts\` from OpenStreetMap data (© OpenStreetMap contributors, ODbL) in this repo's map area`,
  `(Colombo Fort, Pettah and Maradana south to Dehiwala). It lists every building with a name in OSM, plus unnamed buildings ${TALL} m or taller.`,
  '',
  `**${rows.length} buildings** · ★★★ Icon ${count(1)} · ★★ Major ${count(2)} · ★ Local ${count(3)} · modelled ${done}`,
  '',
  '## How to take one',
  '1. Pick an unticked row, starting with ★★★ in your area. Put your name next to it in a PR or issue so nobody doubles up.',
  '2. Follow the steps in [public/data/buildings/README.md](../public/data/buildings/README.md): licensed reference photos only',
  '   (your own, CC-BY or CC-BY-SA, public domain; never Google imagery or AI images), model on the OSM footprint, export the GLB,',
  '   and add the record.',
  '3. Check it with the **in game** link: it opens the simulator at the building. Press `P` to compare with a reference photo.',
  '4. Re-run the script. The row is ticked once its record has a model.',
  '',
  '**Tiers:** ★★★ = a curated landmark (`records.json`) or 80 m and taller · ★★ = named and 25 m or taller, or a civic, religious, office or commercial building ·',
  '★ = other named buildings and unnamed towers. "(est.)" means OSM has no height or levels tag and the height is estimated.',
  '',
  '## By area',
  '',
  ...areas.map(([a, rs]) => `- [${a}](#${a.toLowerCase().replace(/[^a-z0-9 -]/g, '').replace(/ /g, '-')}) (${rs.length})`),
  '',
  ...areas.flatMap(([a, rs]) => [
    `## ${a}`, '',
    '| Done | Building | Tier | Type | Height | OSM | References | Status |',
    '|---|---|---|---|---|---|---|---|',
    ...rs.sort((p, q) => p.tier - q.tier || q.b.h - p.b.h).map(line), '',
  ]),
].join('\n');

writeFileSync(OUT, md);
console.log(`${OUT}: ${rows.length} buildings in ${areas.length} areas (icon ${count(1)}, major ${count(2)}, local ${count(3)}), modelled ${done}`);
